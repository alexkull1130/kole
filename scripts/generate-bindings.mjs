#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";

function usage() {
  console.error("Usage: node scripts/generate-bindings.mjs <manifest.json> <output-directory>");
  process.exit(2);
}

const [manifestPath, outputDirectory] = process.argv.slice(2);
if (!manifestPath || !outputDirectory) usage();
const manifest = JSON.parse(fs.readFileSync(manifestPath, "utf8"));
if (!Array.isArray(manifest.classes)) throw new Error("manifest.classes must be an array");
const identifier = value => value.replace(/[^A-Za-z0-9_]/g, "_");
const koleType = value => value ?? "void";
const lines = ["// Generated by Kole's native binding generator. Do not edit.", ""];
const cLines = ["/* Generated by Kole's native binding generator. */", "#pragma once", "#include <stdint.h>", "", "#ifdef __cplusplus", "extern \"C\" {", "#endif", ""];
for (const cls of manifest.classes) {
  if (!cls.name || !/^[A-Z][A-Za-z0-9_]*$/.test(cls.name)) throw new Error(`invalid class name: ${cls.name}`);
  const closeable = cls.closeable === true;
  lines.push(`native class ${cls.name}${closeable ? " implements Closeable" : ""} {`);
  for (const method of cls.methods ?? []) {
    const params = (method.params ?? []).map(p => `${p.name}: ${koleType(p.type)}`).join(", ");
    lines.push(`    native ${method.name}(${params}) -> ${koleType(method.returns)};`);
  }
  lines.push("}", "");
  const stem = identifier(cls.name).toLowerCase();
  cLines.push(`typedef struct kole_${stem} kole_${stem};`);
  cLines.push(`kole_${stem}* kole_${stem}_create(void);`);
  for (const method of cls.methods ?? []) {
    if (method.name === "close" && closeable) cLines.push(`void kole_${stem}_close(kole_${stem}* value);`);
  }
  cLines.push("");
}
cLines.push("#ifdef __cplusplus", "}", "#endif", "");
fs.mkdirSync(outputDirectory, { recursive: true });
fs.writeFileSync(path.join(outputDirectory, "bindings.k"), lines.join("\n"));
fs.writeFileSync(path.join(outputDirectory, "bindings.h"), cLines.join("\n"));
